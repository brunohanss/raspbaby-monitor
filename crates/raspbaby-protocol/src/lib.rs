//! Bounded messages for the local media feasibility test.
//!
//! Transfer messages by hand through local standard input and output. These
//! messages do not authenticate a peer. Do not expose them as a network service.

use serde::{Deserialize, Serialize};
use std::fmt;
use ts_rs::TS;

pub const PROTOCOL_VERSION: u32 = 1;
pub const MAX_SDP_BYTES: usize = 65_536;
pub const MAX_MESSAGE_BYTES: usize = 98_304;
pub const MAX_SESSION_ID_BYTES: usize = 64;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
pub enum SignalKind {
    #[serde(rename = "webrtc.offer")]
    Offer,
    #[serde(rename = "webrtc.answer")]
    Answer,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct SignalingMessage {
    pub protocol_version: u32,
    #[serde(rename = "type")]
    pub kind: SignalKind,
    pub session_id: String,
    pub sdp: String,
}

impl SignalingMessage {
    pub fn validate(&self) -> Result<(), ProtocolError> {
        if self.protocol_version != PROTOCOL_VERSION {
            return Err(ProtocolError::UnsupportedVersion(self.protocol_version));
        }
        if self.session_id.is_empty()
            || self.session_id.len() > MAX_SESSION_ID_BYTES
            || !self
                .session_id
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'-' | b'_' | b'.'))
        {
            return Err(ProtocolError::InvalidSessionId);
        }
        if self.sdp.is_empty() || self.sdp.len() > MAX_SDP_BYTES {
            return Err(ProtocolError::InvalidSdpSize);
        }
        Ok(())
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum ProtocolError {
    MessageTooLarge,
    InvalidJson,
    UnsupportedVersion(u32),
    InvalidSessionId,
    InvalidSdpSize,
}

impl fmt::Display for ProtocolError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MessageTooLarge => f.write_str("signaling message exceeds the size limit"),
            Self::InvalidJson => f.write_str("invalid signaling JSON or fields"),
            Self::UnsupportedVersion(version) => {
                write!(f, "unsupported protocol major version {version}")
            }
            Self::InvalidSessionId => f.write_str("invalid signaling session ID"),
            Self::InvalidSdpSize => f.write_str("SDP is empty or exceeds the size limit"),
        }
    }
}

impl std::error::Error for ProtocolError {}

/// Check the byte limit before JSON parsing. SDP syntax is checked by WebRTC.
/// Unknown optional fields are ignored to permit compatible extensions.
pub fn parse_message(raw: &str) -> Result<SignalingMessage, ProtocolError> {
    if raw.len() > MAX_MESSAGE_BYTES {
        return Err(ProtocolError::MessageTooLarge);
    }
    let message: SignalingMessage =
        serde_json::from_str(raw).map_err(|_| ProtocolError::InvalidJson)?;
    message.validate()?;
    Ok(message)
}

/// Generate the client contract from the Rust wire types.
pub fn typescript_contract() -> String {
    format!(
        "// Generated by raspbaby-protocol. Do not edit.\nexport {}\nexport {}\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\nexport const MAX_SDP_BYTES = {MAX_SDP_BYTES};\nexport const MAX_MESSAGE_BYTES = {MAX_MESSAGE_BYTES};\nexport const MAX_SESSION_ID_BYTES = {MAX_SESSION_ID_BYTES};\n",
        SignalKind::decl(), SignalingMessage::decl(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn message() -> SignalingMessage {
        SignalingMessage {
            protocol_version: PROTOCOL_VERSION,
            kind: SignalKind::Offer,
            session_id: "spike-1".into(),
            sdp: "v=0\r\n".into(),
        }
    }

    #[test]
    fn round_trip_and_optional_field() {
        let value = message();
        assert_eq!(
            parse_message(&serde_json::to_string(&value).unwrap()),
            Ok(value.clone())
        );
        let mut json = serde_json::to_value(&value).unwrap();
        json["future_field"] = true.into();
        assert_eq!(parse_message(&json.to_string()), Ok(value));
    }

    #[test]
    fn rejects_unsupported_version_and_invalid_type() {
        let mut value = message();
        value.protocol_version = 2;
        assert_eq!(
            parse_message(&serde_json::to_string(&value).unwrap()),
            Err(ProtocolError::UnsupportedVersion(2))
        );
        assert_eq!(
            parse_message(
                r#"{"protocol_version":1,"type":"system.heartbeat","session_id":"s","sdp":"v=0"}"#
            ),
            Err(ProtocolError::InvalidJson)
        );
        assert_eq!(parse_message("{}"), Err(ProtocolError::InvalidJson));
    }

    #[test]
    fn enforces_byte_limits_and_session_ids() {
        assert_eq!(
            parse_message(&" ".repeat(MAX_MESSAGE_BYTES + 1)),
            Err(ProtocolError::MessageTooLarge)
        );
        let mut value = message();
        value.sdp = "x".repeat(MAX_SDP_BYTES);
        assert!(value.validate().is_ok());
        value.sdp.push('x');
        assert_eq!(value.validate(), Err(ProtocolError::InvalidSdpSize));
        value.sdp = "é".repeat(MAX_SDP_BYTES / 2 + 1);
        assert_eq!(value.validate(), Err(ProtocolError::InvalidSdpSize));
        value.sdp = "v=0".into();
        for id in ["".to_owned(), "a".repeat(65), "bad id".into(), "é".into()] {
            value.session_id = id;
            assert_eq!(value.validate(), Err(ProtocolError::InvalidSessionId));
        }
        value.session_id = "s".into();
        value.sdp.clear();
        assert_eq!(value.validate(), Err(ProtocolError::InvalidSdpSize));
    }

    #[test]
    fn generated_contract_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../packages/protocol-client/src/generated.ts");
        if std::env::var_os("UPDATE_PROTOCOL_TYPES").is_some() {
            std::fs::write(&path, typescript_contract()).unwrap();
        }
        assert_eq!(
            std::fs::read_to_string(path).unwrap().replace("\r\n", "\n"),
            typescript_contract(),
            "run with UPDATE_PROTOCOL_TYPES=1 to refresh the client contract"
        );
    }
}
